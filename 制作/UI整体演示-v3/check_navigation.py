"""Exercise function ownership, all three Back inputs, and transactional drafts."""
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

ROOT = Path(__file__).resolve().parents[2]


def run(page, url):
    page.add_init_script(path=Path(__file__).with_name('test_unlocked_shop.js'))
    page.goto(url)
    menu = lambda key: page.select_option('#jump', key)
    click = lambda selector: page.locator(selector).first.click()
    back = lambda: click('#back')
    def route(key):
        page.wait_for_function('k=>location.hash==="#"+k&&displayedPage===k', arg=key)

    menu('rooms')
    click('[data-species="猫"]')
    click('[data-species="狗"]')
    click('[data-dot=pack]')
    page.keyboard.press('Escape')
    route('rooms')
    expect(page.locator('[data-dot=pack]')).to_be_visible()
    page.go_back()
    route('home')
    menu('rooms')
    click('[data-species="猫"]')
    page.evaluate('saleState.coins=4000')
    click('[data-dot=pack]')
    click('[data-dot=pack-commit]')
    click('[data-go=roombreed]')
    route('roombreed')
    # The example male is initially young. Use a mature fixture for this return path.
    page.evaluate("saleState.stock.get('lan').stage='成年';show(displayedPage,true)")
    click('[data-pair=pick][data-key=yun]')
    click('[data-pair=pick][data-key=lan]')
    click('[data-pair=review]')
    page.keyboard.press('Escape')
    assert page.locator('[data-pair=pick][aria-pressed=true]').count()==2
    back()
    route('home')
    menu('rooms')
    click('[data-species="猫"]')
    page.select_option('[data-room-filter=sex]', '母')
    click('.rb-row[data-sale=profile]')
    click('[data-sale=seed]')
    page.keyboard.press('Escape')
    route('rooms')
    assert page.locator('[data-room-filter=sex]').input_value()=='母'
    expect(page.locator('[data-species="猫"]')).to_have_attribute('aria-pressed','true')
    click('[data-go=roomsell]')
    page.locator('[data-sale-pet]').first.check()
    click('[data-sale=review]')
    click('[data-sale=edit]')
    assert page.locator('[data-sale-pet]').first.is_checked()
    click('[data-sale=review]')
    click('#sale-review [data-nav-close]')
    route('rooms')
    expect(page.locator('[data-species="猫"]')).to_have_attribute('aria-pressed','true')
    click('[data-go=roomsell]')
    page.locator('[data-sale-pet=lan]').check()
    click('[data-sale=review]')
    click('[data-sale=commit]')
    route('rooms')
    assert 'lan' not in page.evaluate('Array.from(saleState.stock.keys())')
    assert page.locator('[data-room-filter=sex]').input_value()=='母'
    click('.rb-row[data-sale=profile]')
    assert not page.locator('[data-dot=profile-sale]').count()
    click('[data-sale=seed]')
    click('[data-dot=profile-sale]')
    route('market')
    assert page.locator('[data-sale-pet]:checked').count()==1
    click('[data-sale=review]')
    page.go_back()
    route('market')
    assert page.locator('[data-sale-pet]:checked').count()==1
    back()
    route('home')
    menu('orders')
    click('[data-sale=open][data-key=neighbors]')
    for check in page.locator('[data-sale-pet]').all()[:2]:
        check.check()
    click('[data-sale=review]')
    page.keyboard.press('Escape')
    route('orders')
    click('[data-sale=open][data-key=neighbors]')
    assert not page.locator('input:checked').count()
    page.go_back()
    route('orders')
    click('[data-go=cancelshop]')
    click('[data-dot=buy-review]')
    page.go_back()
    route('orders')
    assert not page.locator('time[data-df-clock]').count()
    menu('guest')
    click('[data-sale=open][data-key=guest]')
    page.go_back()
    route('guest')
    expect(page.locator('[data-dot=guest-dismiss]')).to_be_visible()
    menu('lab')
    click('[data-go=research]')
    click('[data-research=node]')
    click('[data-research=prereq]')
    page.locator('.dr-table summary').click()
    page.go_back()
    route('research')
    assert not page.locator('dialog[open]').count()
    click('[data-sale=open][data-key=recycle]')
    route('lab')
    page.locator('[data-sale-pet=hui]').check()
    click('[data-sale=review]')
    page.keyboard.press('Escape')
    assert page.locator('[data-sale-pet=hui]').is_checked()
    back()
    route('home')
    menu('show')
    click('[data-go=collection]')
    click('[data-dot=book-tab][data-key=private]')
    click('[data-dot=history]')
    page.keyboard.press('Escape')
    route('collection')
    expect(page.locator('[data-dot=book-tab][data-key=private]')).to_have_class('btn primary')
    page.go_back()
    route('home')
    menu('rabbitcheckin')
    click('[data-rabbit=claim]')
    click('.rb-row[data-rabbit=pet]')
    page.go_back()
    route('rabbitcheckin')
    expect(page.locator('.rb-row')).to_have_count(2)
    print(page.viewport_size,'三级返回、交易草稿、跨功能切换、浏览器与 Esc 通过',flush=True)


if __name__=='__main__':
    with sync_playwright() as pw, pw.chromium.launch(channel='msedge') as browser:
        for w,h,path in [(390,844,'美术确认稿/UI整体演示-v3'),(320,568,'手机预览/dist/ui-v3')]:
            p=browser.new_page(viewport={'width':w,'height':h},is_mobile=True,has_touch=True)
            p.set_default_timeout(5500)
            errors=[]
            p.on('pageerror',lambda exc:errors.append(str(exc)))
            run(p,(ROOT/path/'index.html').as_uri())
            assert not errors,errors
            p.close()
