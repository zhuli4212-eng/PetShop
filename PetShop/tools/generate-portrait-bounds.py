"""Record transparent margins for list portraits without changing source images."""
from pathlib import Path
from PIL import Image

project=Path(__file__).resolve().parents[1]
records=[]
for folder in ('pets','pet-young'):
    for path in sorted((project/'assets/resources'/folder).glob('*.png')):
        with Image.open(path) as picture:
            bounds=picture.getchannel('A').getbbox()
            if bounds is None:raise ValueError(f'Empty portrait: {path}')
        records.append(f'    {folder+"/"+path.stem!r}:[{",".join(map(str,bounds))}],')
output=project/'assets/scripts/PetPortraitBounds.ts'
output.write_text('// Generated by tools/generate-portrait-bounds.py; source images remain unchanged.\n'
    'export const petPortraitBounds:Record<string,readonly [number,number,number,number]>={\n'
    +'\n'.join(records)+'\n};\n',encoding='utf-8',newline='\n')
print(f'{len(records)} portrait bounds written to {output}')
