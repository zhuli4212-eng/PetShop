import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { GameStore } from './game-store.mjs';
import { lifeDates, stageOf } from './care.mjs';

test('开店引导按经营事件推进，保存每一步及成交回执，只有首窝使用 5 秒', t=>{
  const dir=mkdtempSync(join(tmpdir(),'petshop-guide-test-'));
  t.after(()=>rmSync(dir,{recursive:true,force:true}));
  let now=Date.UTC(2026,10,18,1),store;
  const options={wall:()=>now,monotonic:()=>0,onboarding:true};
  const reopen=()=>{store=new GameStore(dir,options);store.shop();};
  reopen();
  const page=(key,args={})=>store.page(key,args).page;
  const step=()=>store.shop().onboarding?.step;
  const command=(type,args={})=>{
    const {profileId,version}=store.shop();
    return {type,args,profileId,version,requestId:randomUUID()};
  };
  const act=(type,args)=>store.act(command(type,args));
  const choose=(a)=>store.act(command(a.type,a.args));

  assert.equal(step(),0);
  assert.deepEqual(store.shop().rooms,[]);
  assert.equal(store.state.pets.length,0);
  assert.throws(()=>act('onboarding.openRoom'),/当前引导/);
  act('onboarding.enter');reopen();
  assert.equal(page('onboarding').art,'onboarding/handover-envelope');
  act('onboarding.proceed');
  const open=command('onboarding.openRoom');
  const receipt=store.act(open);
  reopen();
  assert.deepEqual(store.act(open),receipt);
  assert.equal(step(),3);
  assert.equal(store.state.pets.length,2);
  assert.equal(store.state.coins,680);
  assert.ok(store.state.pets.every(p=>p.breedKey==='domestic'&&stageOf(p,now)==='幼年'));
  assert.throws(()=>act('care.checkin'),/完成开店引导/);

  const deathDates=store.state.pets.map(p=>lifeDates(p).deathAt);
  const feed=command('onboarding.feed');
  store.act(feed);reopen();store.act(feed);
  assert.equal(step(),4);
  assert.ok(store.state.pets.every(p=>stageOf(p,now)==='成年'));
  assert.deepEqual(store.state.pets.map(p=>lifeDates(p).deathAt),deathDates);
  assert.equal(store.state.rooms.rabbit.nutrition,undefined);
  const [mother,father]=store.state.onboarding.starters;
  const review=page('breed',{mother,father});
  assert.equal(review.presentation.waitText,'5 秒');
  assert.throws(()=>act('care.breed',{mother:father,father:mother}),/指定的一公一母/);
  choose(review.actions[0]);
  const job=structuredClone(store.state.rooms.rabbit.job);
  assert.equal(step(),5);
  assert.equal(job.endsAt-now,5000);
  now+=4000;reopen();
  assert.equal(step(),5);
  assert.deepEqual(store.state.rooms.rabbit.job.offspring,job.offspring);
  now+=1000;
  assert.equal(step(),6);
  const litter=page('litter');
  const children=litter.rows.filter(r=>r.litterMember);
  assert.equal(children.length,job.offspring.length);
  assert.equal(step(),7);
  page('pet',{id:children[1].animal.id});assert.equal(step(),7);
  assert.equal(page('pet',{id:children[0].animal.id}).presentation.traits.length,6);
  assert.equal(step(),8);

  const market=page('market');
  assert.equal(step(),9);
  assert.deepEqual(market.rows.map(r=>r.select),[mother,father]);
  assert.throws(()=>page('saleQuote',{channel:'market',ids:[mother,father]}),/指定的一只/);
  const quote=page('saleQuote',{channel:'market',ids:[mother]});
  choose(quote.actions[0]);reopen();
  assert.equal(step(),10);
  assert.equal(store.state.onboarding.remainingId,father);
  assert.equal(page('pet',{id:father}).presentation.animal.stage,'成年');
  assert.equal(step(),10);
  assert.equal(page('recycle').rows.length,0);
  assert.equal(step(),10);

  // Fixture only. Present the naturally expired individual without moving store time
  // or changing any other animal's age.
  const expired=structuredClone(store.state);
  const remaining=expired.pets.find(p=>p.id===father);
  remaining.bornAt-=lifeDates(remaining).deathAt-now+1;
  delete remaining.maturation;
  store.save(expired);
  assert.equal(page('pet',{id:father}).presentation.animal.stage,'已故');
  assert.equal(step(),11);
  const recycle=page('recycle');
  assert.equal(step(),12);
  assert.deepEqual(recycle.rows.map(r=>r.select),[father]);
  choose(page('saleQuote',{channel:'recycle',ids:[father]}).actions[0]);
  assert.equal(step(),13);

  const offers=page('lab').rows.map(r=>r.animal);
  assert.equal(offers.length,2);
  assert.ok(offers.every(p=>p.breed==='垂耳兔'&&p.stage==='成年'));
  const purchase=command('onboarding.buy',{id:offers[1].id,price:200});
  const buyReceipt=store.act(purchase);reopen();store.act(purchase);
  assert.deepEqual(store.receipt(purchase.requestId),buyReceipt);
  now+=31*60_000;
  assert.deepEqual(page('lab').rows.map(r=>r.animal.id),offers.map(p=>p.id));
  assert.equal(page('lab').subtitle,'已购买 1 / 2');
  assert.throws(()=>act('onboarding.buy',{id:offers[1].id,price:200}),/已购入/);
  choose(page('offer',{id:offers[0].id}).actions[0]);
  assert.equal(step(),14);
  assert.equal(page('lab').subtitle,'已购买 2 / 2');
  assert.deepEqual(page('breed').presentation.candidates.map(p=>p.sex),['母','公']);
  const pair=Object.fromEntries(offers.map(p=>[p.sex==='母'?'mother':'father',p.id]));
  act('care.breed',pair);
  assert.equal(step(),15);
  assert.equal(store.state.rooms.rabbit.job.endsAt-now,120000);
  const tasks=page('tasks');
  assert.equal(tasks.rows.filter(r=>r.done).length,4);
  const wallet=store.state.coins,xp=store.state.shopXp;
  choose(tasks.actions[0]);
  assert.equal(step(),16);
  assert.equal(store.state.coins,wallet+40);
  assert.equal(store.state.shopXp,xp);
  assert.equal(store.state.rooms.rabbit.nutritionStock.premium,2);
  const orders=page('orders');
  assert.equal(orders.rows.length,3);
  const targetId=orders.rows[0].link.args.id;
  const suitable=page('sale',{channel:'order',targetId}).rows;
  assert.ok(suitable.length>0&&suitable.every(r=>children.some(c=>c.animal.id===r.select)));
  const orderQuote=page('saleQuote',{channel:'order',targetId,ids:[suitable[0].select]});
  assert.match(orderQuote.visual.guideQuote,/自由市场 \d+ 金币 · 本订单 \d+ 金币（×1\.35）/);
  choose(orderQuote.actions[0]);
  assert.equal(step(),17);
  assert.equal(store.state.orders[0].readyAt,now+30*60_000);
  assert.equal(page('onboarding').rows[0].title,'正在培育');
  act('onboarding.finish');reopen();
  assert.equal(step(),undefined);
  assert.equal(page('tasks').actions[0].label,'已领取');
  assert.throws(()=>act('onboarding.claim'),/未识别/);
  assert.equal(store.state.rooms.rabbit.nutritionStock.premium,2);
});

test('已存在的本机店铺不被改成新手档', t=>{
  const dir=mkdtempSync(join(tmpdir(),'petshop-guide-old-'));
  t.after(()=>rmSync(dir,{recursive:true,force:true}));
  const old=new GameStore(dir);
  const {profileId}=old.shop();
  const known=old.state.pets.map(p=>p.id);
  const restored=new GameStore(dir,{onboarding:true});
  assert.equal(restored.shop().profileId,profileId);
  assert.equal(restored.shop().onboarding,undefined);
  assert.deepEqual(restored.state.pets.map(p=>p.id),known);
});
